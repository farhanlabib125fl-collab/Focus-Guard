'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'node_modules', '@fontsource', 'baloo-da-2', 'files');
const OUT = path.join(ROOT, 'fonts');
const WEIGHTS = [500, 600, 700, 800];
const RANGES = {
    latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
    bengali: 'U+0951-0952,U+0964-0965,U+0980-09FE,U+1CF7,U+200C-200D,U+20B9,U+25CC'
};

if (!fs.existsSync(SRC)) {
    console.error('Font package nei. Age chalao:  npm install');
    process.exit(1);
}
fs.mkdirSync(OUT, { recursive: true });

let css = '/* auto-generated by tools/prepare-assets.js -- haat diye bodlio na */\n';
let count = 0;
Object.keys(RANGES).forEach((subset) => {
    WEIGHTS.forEach((w) => {
        const file = `baloo-da-2-${subset}-${w}-normal.woff2`;
        const from = path.join(SRC, file);
        if (!fs.existsSync(from)) { console.warn('missing:', file); return; }
        fs.copyFileSync(from, path.join(OUT, file));
        css += `@font-face{font-family:'Baloo Da 2';font-style:normal;font-display:swap;font-weight:${w};` +
            `src:url(./${file}) format('woff2');unicode-range:${RANGES[subset]};}\n`;
        count++;
    });
});
if (!count) { console.error('Kono font file paoa jaini (package version dekho).'); process.exit(1); }
fs.writeFileSync(path.join(OUT, 'fonts.css'), css);
console.log(`fonts ready: ${count} files -> fonts/`);
